from playwright.sync_api import Page, expect


def test_form(page: Page):
    page.goto("https://www.qa-practice.com/forms/practice-form", wait_until="domcontentloaded")

    first_name_locator = page.locator("#firstName")
    last_name_locator = page.locator("#lastName")
    email_locator = page.locator("#userEmail")
    female_locator = page.locator("[value='Female']")
    mobile_locator = page.locator("#userNumber")
    birthday_locator = page.locator("[placeholder='Date of Birth']")
    subject_locator = page.locator("#subjectsAutocomplete")
    subject_suggestion_locator = page.locator("div#subjectsSuggestions")
    hobby_locator = page.locator("[value='Sports']")
    address_locator = page.locator("#currentAddress")
    state_dropdown_locator = page.locator("#div_id_state .custom-dropdown-control")
    state_option_locator = page.locator(".custom-dropdown-option[data-value='NCR']")
    city_dropdown_locator = page.locator("#div_id_city .custom-dropdown-control")
    city_option_locator = page.locator(".custom-dropdown-option[data-value='Delhi']")
    submit_locator = page.locator("#submit-id-submit")

    first_name_locator.fill("Yuliya")
    last_name_locator.fill("Vinokurova")
    email_locator.fill("yuliyavin@email.com")
    female_locator.check()
    mobile_locator.fill("9110010102")
    birthday_locator.fill("22 Dec 1995")
    subject_locator.fill("eng")
    subject_suggestion_locator.get_by_text("English").click()
    hobby_locator.check()
    address_locator.fill("Tupoleva 13")
    state_dropdown_locator.click()
    state_option_locator.click()
    city_dropdown_locator.click()
    city_option_locator.click()
    submit_locator.click()

    result_title_locator = page.locator("#resultsModalLabel")
    student_name_locator = page.locator("//tr[td[1][text()='Student Name']]/td[2]")
    student_email_locator = page.locator("//tr[td[1][text()='Student Email']]/td[2]")
    gender_locator = page.locator("//tr[td[1][text()='Gender']]/td[2]")
    mob_locator = page.locator("//tr[td[1][text()='Mobile']]/td[2]")
    date_of_birth_locator = page.locator("//tr[td[1][text()='Date of Birth']]/td[2]")
    sub_locator = page.locator("//tr[td[1][text()='Subjects']]/td[2]")
    hobbies_locator = page.locator("//tr[td[1][text()='Hobbies']]/td[2]")
    addr_locator = page.locator("//tr[td[1][text()='Address']]/td[2]")
    state_city_locator = page.locator("//tr[td[1][text()='State and City']]/td[2]")

    expect(result_title_locator).to_have_text("Thanks for submitting the form")
    expect(student_name_locator).to_have_text("Yuliya Vinokurova")
    expect(student_email_locator).to_have_text("yuliyavin@email.com")
    expect(gender_locator).to_have_text("Female")
    expect(mob_locator).to_have_text("9110010102")
    expect(date_of_birth_locator).to_have_text("1995-12-22")
    expect(sub_locator).to_have_text("English")
    expect(hobbies_locator).to_have_text("Sports")
    expect(addr_locator).to_have_text("Tupoleva 13")
    expect(state_city_locator).to_have_text("NCR")
